#Al igual que se puede eliminar elementos de una lista tambien se pueden agregar elementos
#Para ello se utilizan los metodos 'append() o insert()'

#APPEND(parametro):
#Aniade elementos al final de la lista
my_list = [1,2,3]
print(my_list)
my_list.append('hello')
print(my_list)

#INSERT(location, value):
#Puede agregar un elemento en cualquier parte de la lista o simplemente al final
your_list = ['hello', 'love', 'contry']
print(your_list)
your_list.insert(1, 'espaniol')
print(your_list)
