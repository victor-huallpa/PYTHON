#Los indices negativos son permitidos para seleccionar elementos de una lista
#Estos indices seleccionan elementos a apartir del ultimo elemento de la lista considerando al ultimo elemento de la lista como indice -1

my_list = ['a', 1, 'hello world', 2]
print(f"El indice -1 de la lista contiene: {my_list[-1]}")#Ultimo elemento de la lista
print(f"El indice -2 de la lista contiene: {my_list[-2]}")#Penultimo elemento de la lista
print(f"El indice -3 de la lista contiene: {my_list[-3]}")
print(f"El indice -4 de la lista contiene: {my_list[-4]}")